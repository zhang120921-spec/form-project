/**
 * Translate an English source string. Supports `{param}` interpolation.
 *   t("You have {n} rounds to confirm", { n: 3 })
 */
export function t(en: string, params?: Record<string, string | number>): string {
  let out = lang === "zh" && Object.prototype.hasOwnProperty.call(ZH, en) ? ZH[en] : en;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      out = out.split(`{${k}}`).join(String(v));
    }
  }
  return out;
}
